// Email notification service using Resend
// Sends enquiry details to ai-labs@hexanovate.com on every form submission

const { Resend } = require('resend');

let _resend = null;

function getResendClient() {
  if (_resend) return _resend;
  const apiKey = process.env.RESEND_API_KEY;
  if (!apiKey) {
    console.warn('[Email] RESEND_API_KEY not set — skipping email notification');
    return null;
  }
  _resend = new Resend(apiKey);
  return _resend;
}

/**
 * Sends notification email to ai-labs@hexanovate.com
 * @param {Object} data - Lead form data
 * @returns {Promise<{success: boolean, error?: string}>}
 */
async function sendLeadNotification(data) {
  const resend = getResendClient();
  if (!resend) return { success: false, error: 'Email not configured' };

  const notifyTo = process.env.NOTIFY_EMAIL || 'ai-labs@hexanovate.com';
  const fromAddress = process.env.EMAIL_FROM || 'leads@klearstack.com';
  const timestamp = new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' });

  const html = `
    <div style="font-family: Inter, sans-serif; max-width: 600px; margin: 0 auto; padding: 24px; border: 1px solid #e2e8f0; border-radius: 12px;">
      <div style="display: flex; align-items: center; margin-bottom: 24px;">
        <h1 style="color: #1a4fba; font-size: 22px; margin: 0;">✦ KlearStack — New Lead</h1>
      </div>
      <p style="color: #475569; margin-bottom: 20px;">A new enquiry was received at <strong>${timestamp} IST</strong></p>

      <table style="width: 100%; border-collapse: collapse; font-size: 14px;">
        ${[
          ['Name', data.name],
          ['Email', data.email],
          ['Contact Number', data.contactNo],
          ['Solution Required', data.solutionRequired],
          ['No. of Documents', data.noOfDocuments],
          ['Pain Points & Expectations', data.painPointExpectations || '—'],
        ].map(([label, value]) => `
          <tr style="border-bottom: 1px solid #f1f5f9;">
            <td style="padding: 10px 12px; font-weight: 600; color: #0f172a; width: 40%; background: #f8fafc;">${label}</td>
            <td style="padding: 10px 12px; color: #475569;">${value}</td>
          </tr>
        `).join('')}
      </table>

      <div style="margin-top: 24px; padding: 12px; background: #eff6ff; border-radius: 8px; font-size: 12px; color: #1a4fba;">
        This email was automatically generated by the KlearStack lead capture system.
      </div>
    </div>
  `;

  try {
    const result = await resend.emails.send({
      from: fromAddress,
      to: notifyTo,
      subject: `New Demo Request — ${data.name} (${data.solutionRequired})`,
      html,
    });

    if (result.error) {
      console.error('[Email] Resend error:', result.error);
      return { success: false, error: result.error.message };
    }

    console.info('[Email] Notification sent, id:', result.data?.id);
    return { success: true };
  } catch (err) {
    console.error('[Email] Error:', err.message);
    return { success: false, error: err.message };
  }
}

module.exports = { sendLeadNotification };
